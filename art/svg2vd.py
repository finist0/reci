"""Convert the small SVG subset that izba.py emits into an Android VectorDrawable.

Supported: svg viewBox, g with translate/scale/rotate, rect, circle, ellipse,
polygon, polyline and path, with fill, stroke, stroke-width, stroke-linecap,
stroke-linejoin and opacity on the shape itself (no inheritance).
"""
import re
import xml.etree.ElementTree as ET

NS = "{http://www.w3.org/2000/svg}"


def _f(v):
    return f"{float(v):g}"


def _shape_path(el):
    tag = el.tag[len(NS):]
    a = el.attrib
    if tag == "path":
        return a["d"]
    if tag == "rect":
        x, y, w, h = (float(a.get(k, 0)) for k in ("x", "y", "width", "height"))
        r = min(float(a.get("rx", 0)), w / 2, h / 2)
        if not r:
            return f"M{x:g},{y:g} h{w:g} v{h:g} h{-w:g} z"
        return (f"M{x + r:g},{y:g} h{w - 2 * r:g} a{r:g},{r:g} 0 0 1 {r:g},{r:g} v{h - 2 * r:g} "
                f"a{r:g},{r:g} 0 0 1 {-r:g},{r:g} h{-(w - 2 * r):g} a{r:g},{r:g} 0 0 1 {-r:g},{-r:g} "
                f"v{-(h - 2 * r):g} a{r:g},{r:g} 0 0 1 {r:g},{-r:g} z")
    if tag in ("circle", "ellipse"):
        cx, cy = float(a["cx"]), float(a["cy"])
        rx = float(a.get("r", a.get("rx")))
        ry = float(a.get("r", a.get("ry")))
        return (f"M{cx - rx:g},{cy:g} a{rx:g},{ry:g} 0 1 0 {2 * rx:g},0 "
                f"a{rx:g},{ry:g} 0 1 0 {-2 * rx:g},0 z")
    if tag in ("polygon", "polyline"):
        pts = a["points"].split()
        d = "M" + pts[0] + "".join(" L" + p for p in pts[1:])
        return d + (" z" if tag == "polygon" else "")
    raise ValueError(f"unsupported element <{tag}>")


def _color(v):
    return None if v in (None, "none") else v


def _path(el, out, ind):
    a = el.attrib
    attrs = [f'android:pathData="{_shape_path(el)}"']
    fill = _color(a.get("fill", "#000000" if el.tag != NS + "path" else None))
    stroke = _color(a.get("stroke"))
    op = a.get("opacity")
    if fill:
        attrs.append(f'android:fillColor="{fill}"')
        if op:
            attrs.append(f'android:fillAlpha="{op}"')
    if stroke:
        attrs.append(f'android:strokeColor="{stroke}"')
        attrs.append(f'android:strokeWidth="{_f(a.get("stroke-width", 1))}"')
        if "stroke-linecap" in a:
            attrs.append(f'android:strokeLineCap="{a["stroke-linecap"]}"')
        if "stroke-linejoin" in a:
            attrs.append(f'android:strokeLineJoin="{a["stroke-linejoin"]}"')
        if op:
            attrs.append(f'android:strokeAlpha="{op}"')
    if not fill and not stroke:
        return
    sep = "\n" + ind + "    "
    out.append(f"{ind}<path{sep}{sep.join(attrs)} />")


def _group(el, out, ind):
    attrs = []
    for fn, args in re.findall(r"(\w+)\(([^)]*)\)", el.attrib.get("transform", "")):
        v = [float(x) for x in re.split(r"[ ,]+", args.strip())]
        if fn == "translate":
            attrs += [f'android:translateX="{v[0]:g}"', f'android:translateY="{v[1] if len(v) > 1 else 0:g}"']
        elif fn == "scale":
            attrs += [f'android:scaleX="{v[0]:g}"', f'android:scaleY="{v[-1]:g}"']
        elif fn == "rotate":
            attrs.append(f'android:rotation="{v[0]:g}"')
            if len(v) == 3:
                attrs += [f'android:pivotX="{v[1]:g}"', f'android:pivotY="{v[2]:g}"']
        else:
            raise ValueError(f"unsupported transform {fn}")
    # VectorDrawable scales and rotates before it translates, so only
    # "translate(...) scale(...)" (or a single transform) converts faithfully.
    out.append(f"{ind}<group {' '.join(attrs)}>")
    _children(el, out, ind + "    ")
    out.append(f"{ind}</group>")


def _children(el, out, ind):
    for ch in el:
        if ch.tag == NS + "g":
            _group(ch, out, ind)
        else:
            _path(ch, out, ind)


def svg2vd(text):
    root = ET.fromstring(text)
    _, _, w, h = (float(x) for x in root.attrib["viewBox"].split())
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by art/izba.py, do not edit. -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           f'    android:width="{w:g}dp"',
           f'    android:height="{h:g}dp"',
           f'    android:viewportWidth="{w:g}"',
           f'    android:viewportHeight="{h:g}">']
    _children(root, out, "    ")
    out.append("</vector>")
    return "\n".join(out) + "\n"
